/**
  **************************************************************************
  * @file     delay.c
  * @brief    延时实现：基于 Cortex-M4 内核 DWT->CYCCNT 周期计数器忙等
  *
  * 说明：
  *   delay_init 使能 DWT 计数器（约 4.2ns/计数 @240MHz）；delay_us/delay_ms
  *   通过无符号差值比较实现，CYCCNT 32 位回绕时依然正确。注意本模块
  *   为忙等延时，阻塞 CPU，仅用于上电初始化等场景。
  **************************************************************************
  */

#include "delay.h"

/* 每微秒对应的 DWT 计数个数（delay_init 时根据主频计算） */
static uint32_t s_fac_us = 240;

/*********************************************************************
 * 函 数 名: delay_init
 * 入口参数: 无
 * 出口参数: 无
 * 返 回 值: void
 * 函数功能: 使能 DWT 周期计数器并计算微秒换算因子
 * 说    明: 依赖全局 system_core_clock, 必须在系统时钟配置完成后调用
 * 修改历史:
 *   1.修改人: CodeBuddy
 *     修改日期: 2026年10月14日
 *     修改内容: 重构为纯 DWT 实现(原 SysTick 方式已让给 FreeRTOS 调度器)
 **********************************************************************/
void delay_init(void)
{
  /* ---- Step1: 计算每微秒计数个数 ---- */
  s_fac_us = system_core_clock / 1000000U;

  /* ---- Step2: 使能 DWT 周期计数器(CYCCNT) ---- */
  CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
  DWT->CYCCNT = 0;
  DWT->CTRL |= DWT_CTRL_CYCCNTENA_Msk;
}

/*********************************************************************
 * 函 数 名: delay_us
 * 入口参数: nus     延时微秒数
 * 出口参数: 无
 * 返 回 值: void
 * 函数功能: DWT 周期计数器忙等延时, 精度 1 个系统时钟周期
 * 说    明: 差值无符号环回比较, CYCCNT 回绕时仍正确
 * 修改历史:
 *   1.修改人: CodeBuddy
 *     修改日期: 2026年10月14日
 *     修改内容: 重构为纯 DWT 实现
 **********************************************************************/
void delay_us(uint32_t nus)
{
  uint32_t start = DWT->CYCCNT;                   /* 记录起始周期数 */
  uint32_t cycles = nus * s_fac_us;

  while((DWT->CYCCNT - start) < cycles)
  {
    /* 忙等 */
  }
}

/*********************************************************************
 * 函 数 名: delay_ms
 * 入口参数: nms     延时毫秒数
 * 出口参数: 无
 * 返 回 值: void
 * 函数功能: 毫秒级忙等延时(按 1ms 分段调用 delay_us)
 * 说    明: CYCCNT 32 位计数 240MHz 下约 17.9s 回绕, 分段可支持任意时长
 * 修改历史:
 *   1.修改人: CodeBuddy
 *     修改日期: 2026年10月14日
 *     修改内容: 重构为纯 DWT 实现
 **********************************************************************/
void delay_ms(uint32_t nms)
{
  while(nms--)
  {
    delay_us(1000U);
  }
}
